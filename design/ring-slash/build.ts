// Builds the ring-slash mark: the design SVGs, the app's icons (src/icons) and the paths the in-app
// mark draws (src/components/markPaths.ts). PNGs are rendered by headless Chrome.
// Run: bun design/ring-slash/build.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { launchChrome, Page } from "../../tests/chromePage";
import { GRADIENT } from "./geometry";
import { GRAIN, SMALL_SHADE, TILES, faviconSvg, full, markSvg, outlinedSvg, small, tileSvg } from "./svg";

const here = import.meta.dir;
const root = join(here, "../..");
const icons = join(root, "src/icons");
for (const dir of [join(here, "svg"), join(here, "png"), icons]) mkdirSync(dir, { recursive: true });

const tile = (name: keyof typeof TILES) => tileSvg(TILES[name].kind, TILES[name]);
const designs: Record<string, string> = {
  "mark-full-white": markSvg("full", "#fff"),
  "mark-full-black": markSvg("full", "#000"),
  "mark-small-white": markSvg("small", "#fff"),
  "mark-small-black": markSvg("small", "#000"),
  favicon: faviconSvg(),
  "favicon-ico-16": outlinedSvg("small", 16),
  "favicon-ico-32": outlinedSvg("small", 32),
  "favicon-ico-48": outlinedSvg("full", 48),
  "app-icon": tile("app"),
  "apple-touch-icon": tile("appleTouch"),
  "maskable-icon": tile("maskable"),
};
for (const [name, svg] of Object.entries(designs)) writeFileSync(join(here, "svg", `${name}.svg`), svg);
writeFileSync(join(icons, "favicon.svg"), designs.favicon!);

// The in-app mark draws these with the theme's text colour.
const [[x1, y1], [x2, y2]] = GRADIENT;
const fixed = (v: number) => +v.toFixed(2);
writeFileSync(
  join(root, "src/components/markPaths.ts"),
  `// Generated by design/ring-slash/build.ts: edit the design there and run it again.
export const MARK = ${JSON.stringify(
    {
      full,
      small,
      gradient: [x1, y1, x2, y2].map(fixed),
      grain: GRAIN,
      smallShade: SMALL_SHADE,
    },
    null,
    2,
  )} as const;
`,
);

/** A 32-bit ICO holding PNGs (Windows Vista onwards and every browser read these). */
function ico(images: { size: number; png: Uint8Array }[]) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, png }, i) => {
    const at = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, at);
    header.writeUInt8(size >= 256 ? 0 : size, at + 1);
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(png.byteLength, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += png.byteLength;
  });
  return Buffer.concat([header, ...images.map((i) => Buffer.from(i.png))]);
}

const chrome = await launchChrome();
try {
  const page = await Page.open(chrome.ws, "about:blank", 512, 512, "true");
  await page.send("Emulation.setDefaultBackgroundColorOverride", { color: { r: 0, g: 0, b: 0, a: 0 } });
  const render = async (svg: string, size: number): Promise<Uint8Array> => {
    await page.send("Emulation.setDeviceMetricsOverride", { width: size, height: size, deviceScaleFactor: 1, mobile: false });
    const src = `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
    await page.eval(`(async () => {
      document.documentElement.style.cssText = "margin:0;background:transparent";
      document.body.style.cssText = "margin:0;background:transparent";
      document.body.innerHTML = '<img width="${size}" height="${size}" style="display:block">';
      const img = document.body.firstChild;
      img.src = ${JSON.stringify(src)};
      await img.decode();
      await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
    })()`);
    const shot = await page.send("Page.captureScreenshot", { format: "png", clip: { x: 0, y: 0, width: size, height: size, scale: 1 } });
    return new Uint8Array(Buffer.from(shot.data, "base64"));
  };

  writeFileSync(join(icons, "favicon.ico"), ico([
    { size: 16, png: await render(designs["favicon-ico-16"]!, 16) },
    { size: 32, png: await render(designs["favicon-ico-32"]!, 32) },
    { size: 48, png: await render(designs["favicon-ico-48"]!, 48) },
  ]));
  writeFileSync(join(icons, "apple-touch-icon.png"), await render(designs["apple-touch-icon"]!, 180));
  writeFileSync(join(icons, "icon-192.png"), await render(designs["app-icon"]!, 192));
  writeFileSync(join(icons, "icon-512.png"), await render(designs["app-icon"]!, 512));
  writeFileSync(join(icons, "icon-maskable-512.png"), await render(designs["maskable-icon"]!, 512));
  for (const name of ["mark-full-white", "mark-full-black", "mark-small-white", "mark-small-black"]) {
    writeFileSync(join(here, "png", `${name}.png`), await render(designs[name]!, name.includes("small") ? 64 : 512));
  }
} finally {
  await chrome.close();
}
console.log("Built the ring-slash mark into design/ring-slash, src/icons and src/components/markPaths.ts");
